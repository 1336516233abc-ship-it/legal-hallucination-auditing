"""
ContractNLI dataset processor.
Converts ContractNLI NLI format to legal QA format.

Dataset: https://stanfordnlp.github.io/contract-nli/
Task: Natural Language Inference on contracts
Labels: Entailment, Contradiction, Neutral

Author: Li Xinru (3036807959)
"""

import json
import os
import argparse
from typing import List, Dict
import logging

if __package__:
    from .dataset_loader import DatasetLoader, LegalExample, get_dataset_statistics
else:
    from dataset_loader import DatasetLoader, LegalExample, get_dataset_statistics

logging.basicConfig(level=logging.INFO)
logger = logging.getLogger(__name__)


class ContractNLIProcessor(DatasetLoader):
    """Processor for ContractNLI dataset."""

    def __init__(self, data_dir: str = "data"):
        super().__init__(os.path.join(data_dir, "processed"))
        self.raw_dir = os.path.join(data_dir, "raw", "contractnli")
        os.makedirs(self.raw_dir, exist_ok=True)

    def download(self):
        """Download ContractNLI dataset from HuggingFace."""
        logger.info("Downloading ContractNLI dataset...")
        from datasets import load_dataset

        try:
            dataset = load_dataset("coastalcph/lex_glue", "contract_nli")

            # Save raw data
            for split in ["train", "validation", "test"]:
                if split in dataset:
                    output_path = os.path.join(self.raw_dir, f"{split}.json")
                    data = [dict(item) for item in dataset[split]]
                    with open(output_path, 'w', encoding='utf-8') as f:
                        json.dump(data, f, indent=2, ensure_ascii=False)
                    logger.info(f"Saved {len(data)} {split} examples to {output_path}")

            logger.info("ContractNLI download complete!")
            return dataset

        except Exception as e:
            logger.error(f"Error downloading ContractNLI: {e}")
            raise

    def process(self, split: str = "test") -> List[LegalExample]:
        """
        Process ContractNLI data into standard format.

        Args:
            split: Dataset split (train/validation/test)

        Returns:
            List of LegalExample objects
        """
        logger.info(f"Processing ContractNLI {split} split...")

        raw_path = os.path.join(self.raw_dir, f"{split}.json")
        if not os.path.exists(raw_path):
            logger.warning(f"Raw file not found: {raw_path}. Attempting download...")
            self.download()

        with open(raw_path, 'r', encoding='utf-8') as f:
            raw_data = json.load(f)

        examples = []
        for idx, item in enumerate(raw_data):
            # Convert hypothesis to query
            query = self._hypothesis_to_query(item.get("hypothesis", ""))

            # Get premise (contract text) as context
            context = item.get("premise", "")

            # Get label: 0=entailment, 1=contradiction, 2=neutral
            label_map = {0: "entailment", 1: "contradiction", 2: "neutral"}
            label = label_map.get(item.get("label"), "neutral")

            # Extract evidence spans if available
            evidence_spans = self._extract_evidence_spans(item)

            example = LegalExample(
                id=f"contractnli_{split}_{idx}",
                query=query,
                context=context,
                answer=None,  # Will be generated by system
                label=label,
                evidence_spans=evidence_spans,
                metadata={
                    "dataset": "contractnli",
                    "split": split,
                    "original_hypothesis": item.get("hypothesis", ""),
                }
            )
            examples.append(example)

        logger.info(f"Processed {len(examples)} ContractNLI examples")

        # Print statistics
        stats = get_dataset_statistics(examples)
        logger.info(f"Dataset statistics: {stats}")

        # Save processed data
        self.save_processed(examples, f"contractnli_{split}.json")

        return examples

    def _hypothesis_to_query(self, hypothesis: str) -> str:
        """
        Convert NLI hypothesis to a natural question.

        Example:
        Hypothesis: "The contract can be terminated with 30 days notice"
        Query: "Can the contract be terminated with 30 days notice?"
        """
        # Simple heuristic: add question mark if not present
        if not hypothesis.endswith("?"):
            # Check if it's already in question form
            question_words = ["who", "what", "when", "where", "why", "how", "can", "does", "is", "are"]
            if any(hypothesis.lower().startswith(word) for word in question_words):
                return hypothesis + "?"
            else:
                return f"Is it true that {hypothesis.lower()}?"
        return hypothesis

    def _extract_evidence_spans(self, item: Dict) -> List[tuple]:
        """
        Extract character-level evidence spans from the item.
        ContractNLI may include span annotations.
        """
        # Check if spans are provided in metadata
        if "spans" in item and item["spans"]:
            return [(span["start"], span["end"]) for span in item["spans"]]

        # If no explicit spans, return empty list
        # Evidence retrieval will need to find these
        return []

    def load(self, split: str = "test") -> List[LegalExample]:
        """Load processed ContractNLI dataset."""
        try:
            return self.load_processed(f"contractnli_{split}.json")
        except FileNotFoundError:
            logger.info(f"Processed file not found. Processing {split} split...")
            return self.process(split)


def main():
    parser = argparse.ArgumentParser(description="Process ContractNLI dataset")
    parser.add_argument("--download", action="store_true", help="Download dataset")
    parser.add_argument("--process", action="store_true", help="Process dataset")
    parser.add_argument("--split", type=str, default="test", help="Dataset split")
    parser.add_argument("--data_dir", type=str, default="data", help="Data directory")

    args = parser.parse_args()

    processor = ContractNLIProcessor(data_dir=args.data_dir)

    if args.download:
        processor.download()

    if args.process:
        processor.process(split=args.split)

    if not args.download and not args.process:
        # Default: load existing data
        examples = processor.load(split=args.split)
        logger.info(f"Loaded {len(examples)} examples")
        logger.info(f"First example: {examples[0]}")


if __name__ == "__main__":
    main()